import { create } from 'zustand'

export type SupportedLanguage = 'en' | 'hi' | 'kn' | 'te' | 'ta'

export const SUPPORTED_LANGUAGES: { code: SupportedLanguage; label: string; native: string }[] = [
  { code: 'en', label: 'English', native: 'English' },
  { code: 'hi', label: 'Hindi', native: 'हिन्दी' },
  { code: 'kn', label: 'Kannada', native: 'ಕನ್ನಡ' },
  { code: 'te', label: 'Telugu', native: 'తెలుగు' },
  { code: 'ta', label: 'Tamil', native: 'தமிழ்' },
]

export interface LanguageState {
  language: SupportedLanguage
  setLanguage: (lang: SupportedLanguage) => void
}

export const useLanguageStore = create<LanguageState>(set => ({
  language: (() => {
    const saved = localStorage.getItem('medflow-language') as SupportedLanguage
    if (saved && ['en', 'hi', 'kn', 'te', 'ta'].includes(saved)) {
      return saved
    }
    return 'en'
  })(),
  setLanguage: (language: SupportedLanguage) => {
    localStorage.setItem('medflow-language', language)
    set({ language })
  },
}))

